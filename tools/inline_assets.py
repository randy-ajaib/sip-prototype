#!/usr/bin/env python3
"""Embed every file in assets/ into index.html as data URIs.

Some viewers (the Claude browser panel's file preview, email attachments) open index.html
without access to the folder next to it, so linked images break. Run this after adding or
changing a file in assets/:

    python3 tools/inline_assets.py

It rewrites the block between the ASSETS:BEGIN and ASSETS:END markers in index.html.
The page looks images up with A('assets/…'), which falls back to the plain path.
"""
import base64, json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
page = root / 'index.html'
mime = {'.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp'}
files = sorted(p for p in (root / 'assets').rglob('*') if p.suffix.lower() in mime)
data = {p.relative_to(root).as_posix(): f'data:{mime[p.suffix.lower()]};base64,{base64.b64encode(p.read_bytes()).decode()}' for p in files}
block = '/* ASSETS:BEGIN — generated by tools/inline_assets.py, do not edit by hand */\nconst ASSETS = ' + json.dumps(data, separators=(',', ':')) + ';\n/* ASSETS:END */'
src = page.read_text()
out, n = re.subn(r'/\* ASSETS:BEGIN.*?/\* ASSETS:END \*/', lambda _: block, src, flags=re.S)
if n != 1:
    raise SystemExit('ASSETS:BEGIN / ASSETS:END markers not found in index.html')
page.write_text(out)
print(f'Embedded {len(data)} assets ({sum(len(v) for v in data.values()) // 1024} KB) into {page.name}')
